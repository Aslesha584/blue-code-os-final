import { ArrowLeft, Building2, CheckCircle2, CircleHelp, ExternalLink, Mail, MapPin, Sparkles, Target, Users } from "lucide-react";
import { Link, useNavigate, useParams } from "react-router-dom";
import { usePrototype } from "../context/PrototypeContext";
import { PageHeader, Pill } from "../components/UI";

const pendingLabels = { trigger: "No sample event has been added to this record yet.", signal: "No sample business signal has been added to this record yet.", intent: "No active evaluation evidence has been recorded in this sample." };

function EvidenceCard({ title, value, description, status, source }) {
  return <article className="evidence-detail-card">
    <div className="evidence-detail-top">
      <span>{title}</span>
      <Pill tone={status === "Verified" ? "green" : status === "Inferred / unverified" ? "orange" : "neutral"}>{status}</Pill>
    </div>
    <strong>{value}</strong>
    <p>{description}</p>
    <small><b>Evidence:</b> {source}</small>
  </article>;
}

export default function ProspectIntelligence() {
  const { id } = useParams();
  const navigate = useNavigate();
  const { prospects, outreach, createOutreachForProspects, selectProspect, updateProspectStatus } = usePrototype();
  const p = prospects.find(item => String(item.id) === String(id)) || prospects[0];

  if (!p) {
    return <div><PageHeader title="Prospect not found" description="This prospect is not part of the current sample workspace." /><Link className="back-link" to="/prospects"><ArrowLeft size={16} /> Back to prospects</Link></div>;
  }

  const openSelectedOutreach = () => {
    const existingDraft = outreach.find(item => String(item.prospectId) === String(p.id));
    if (!existingDraft) createOutreachForProspects([p.id]);
    selectProspect(p.id);
    navigate(`/outreach?prospectId=${encodeURIComponent(p.id)}`);
  };

  const score = Number(p.score ?? p.icpFitScore ?? 0);
  const priority = score >= 90 ? "Hot" : score >= 70 ? "High" : score >= 50 ? "Medium" : "Low";
  const source = p.source || p.sourceUrl || "Illustrative demo record · no source link attached";
  const triggerAvailable = Boolean(p.trigger && !/no verified|unavailable|unknown/i.test(p.trigger));
  const buyingSignalAvailable = Boolean(p.buyingSignal && !/unavailable|unknown/i.test(p.buyingSignal));
  const intentEvidence = p.buyingIntentEvidence || p.intentEvidence || "";
  const triggerStatus = p.triggerVerified === true ? "Verified" : triggerAvailable ? "Inferred / unverified" : "Research pending";
  const buyingSignalStatus = p.buyingSignalVerified === true ? "Verified" : buyingSignalAvailable ? "Inferred / unverified" : "Research pending";
  const intentStatus = p.intentVerified === true && intentEvidence ? "Verified" : intentEvidence ? "Inferred / unverified" : "Research pending";

  return <div>
    <Link className="back-link" to="/prospects"><ArrowLeft size={16} /> Back to prospects</Link>
    <PageHeader eyebrow="PROSPECT INTELLIGENCE" title={p.company} description={p.description || "Sample company context for this prospect."} action={<Pill tone={priority.toLowerCase()}>{priority} priority</Pill>} />
    <div className="intelligence-grid">
      <div className="intelligence-main">
        <section className="panel score-panel">
          <div className="score-ring-wrap"><div className="score-ring" style={{ "--score": `${score}%` }}><div><strong>{score}</strong><span>FIT SCORE</span></div></div></div>
          <div className="score-explanation"><div className="eyebrow">WHY THIS PROSPECT RANKS HERE</div><h2>Fit is not proof of purchase intent.</h2><p>The displayed score is the existing prototype score. It is not a probability of purchase and is not generated by a live model.</p><div className="fit-reasons">{(p.fit || []).map(reason => <div key={reason}><CheckCircle2 size={16} />{reason}</div>)}</div></div>
        </section>

        <section className="panel">
          <div className="panel-heading"><div><h2><Sparkles size={18} /> Prospect evidence</h2><p>Three separate signals help explain timing, potential need and active evaluation.</p></div><Pill tone="blue">Demo research</Pill></div>
          <div className="evidence-grid evidence-grid-detailed">
            <EvidenceCard
              title="TRIGGER"
              value={triggerAvailable ? p.trigger : pendingLabels.trigger}
              description="A recent company event that may create a need — for example, funding, a leadership appointment or expansion. A trigger alone does not prove a problem or purchase intent."
              status={triggerStatus}
              source={p.triggerSource || (triggerAvailable ? source : "Demo record · source link not attached")}
            />
            <EvidenceCard
              title="MAIN SIGNAL"
              value={buyingSignalAvailable ? p.buyingSignal : pendingLabels.signal}
              description="An observable business situation that may point to a challenge your product can solve. Treat it as a hypothesis until evidence confirms it."
              status={buyingSignalStatus}
              source={p.buyingSignalSource || p.evidence || (buyingSignalAvailable ? source : "Demo record · source link not attached")}
            />
            <EvidenceCard
              title="INTENT"
              value={intentEvidence || pendingLabels.intent}
              description="Credible evidence that the company is actively looking for or evaluating a solution, such as an RFP, public request or explicit evaluation. Hiring or growth alone is not intent."
              status={intentStatus}
              source={p.intentSource || (intentEvidence ? source : "Demo record · no intent source attached")}
            />
          </div>
          <div className="evidence-integrity-note"><CircleHelp size={16} /><span>Demo records are illustrative. Verified evidence is distinguished from inferred context and research still to be completed. An outreach reply is not the same as pre-purchase intent.</span></div>
          <div className="reply-status-note"><strong>Outreach reply status:</strong> {p.replyReceived ? (p.replyIntent || p.intent || "Reply received") : "No reply recorded"} <span>· This describes a response to outreach, not pre-purchase intent.</span></div>
        </section>

        <section className="panel">
          <div className="panel-heading"><div><h2>Suggested next step</h2><p>Human-reviewed recommendation based on this sample record.</p></div></div>
          <div className="next-step-card"><div className="next-step-number">01</div><div><strong>{p.replyReceived ? "Review the reply and decide on the next conversation step" : String(p.status).toLowerCase().includes("follow-up") ? "Review the suggested follow-up message" : "Validate the context, then review a personalized draft"}</strong><p>Confirm the account is relevant, check the contact and source evidence, and edit the message to match your voice.</p><div className="next-step-actions"><button type="button" onClick={openSelectedOutreach} className="button button-primary"><Mail size={15} /> Review this company’s email</button><button className="button button-secondary" onClick={() => updateProspectStatus(p.id, "Research needed")}>Mark for more research</button></div></div></div>
        </section>
      </div>

      <aside className="intelligence-side">
        <section className="panel"><div className="panel-heading"><h2>Company snapshot</h2><Building2 size={17} className="muted-icon" /></div><div className="snapshot-list"><div><span>Industry</span><strong>{p.industry || "Not specified"}</strong></div><div><span>Company size</span><strong>{p.size || "Not specified"}</strong></div><div><span>Location</span><strong><MapPin size={13} /> {p.location || "Not specified"}</strong></div><div><span>Website</span><strong>{p.website || "Website not added to this sample"}</strong></div></div><div className="source-note">Company evidence: {source}</div></section>
        <section className="panel"><div className="panel-heading"><h2>Decision-maker</h2><Users size={17} className="muted-icon" /></div><div className="contact-card"><div className="contact-avatar">{(p.person || "N").split(" ").map(x => x[0]).join("")}</div><div><strong>{p.person || "Contact not added to this sample"}</strong><span>{p.role || "Role not verified"}</span><small>{p.email || "Email not added to this sample"}</small></div></div><div className="source-note">Demo contact details are illustrative. Confirm identity and email before use.</div><button className="button button-secondary button-full" onClick={() => alert("This is a preview of the contact-enrichment step. Connect a data provider to populate verified details.")}><ExternalLink size={15} /> Preview contact enrichment</button></section>
        <section className="panel"><h2>Workflow status</h2><Pill tone="blue">{p.status}</Pill><div className="form-field status-select"><label>Change demo status</label><select className="input" value={p.status} onChange={e => updateProspectStatus(p.id, e.target.value)}><option>Research needed</option><option>Ready to contact</option><option>Contacted</option><option>Follow-up due</option><option>Interested</option><option>Meeting requested</option><option>Meeting booked</option><option>Not a fit</option></select></div></section>
      </aside>
    </div>
  </div>;
}
